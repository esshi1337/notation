/** One Markdown note that contains every corpus entry, in order. */
export function corpusNote(entries) {
  return entries.map((entry, index) => entry.d || entry.s.includes('\n') ? `Entry ${index}:\n\n$$\n${entry.s}\n$$\n` : `Entry ${index}: $${entry.s}$ end.\n`).join('\n');
}
